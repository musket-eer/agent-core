#!/usr/bin/env bash
# setup_nginx_https.sh
# Idempotent script to configure HTTPS on an nginx container and proxy to an upstream container.

set -euo pipefail

### ====== CONFIGURABLE VARS ======
DOMAIN="${DOMAIN:-api.mostlearned.xyz}"
NGINX_CONTAINER="${NGINX_CONTAINER:-nginx}"
UPSTREAM_CONTAINER="${UPSTREAM_CONTAINER:-agent-core}"
UPSTREAM_HOST="${UPSTREAM_HOST:-agent-core}"
UPSTREAM_PORT="${UPSTREAM_PORT:-8080}"
DOCKER_NETWORK="${DOCKER_NETWORK:-web}"

# Paths INSIDE the nginx container. Your compose mounts should map LE certs here.
CERT_FULLCHAIN_CONT="${CERT_FULLCHAIN_CONT:-/etc/nginx/ssl/fullchain.pem}"
CERT_PRIVKEY_CONT="${CERT_PRIVKEY_CONT:-/etc/nginx/ssl/privkey.pem}"

# Optional: also create an HTTP->HTTPS redirect server block (only works if host publishes :80)
ENABLE_HTTP_REDIRECT="${ENABLE_HTTP_REDIRECT:-false}"
### =================================

die() { echo "ERROR: $*" >&2; exit 1; }
info() { echo -e "\033[1;34m[INFO]\033[0m $*"; }
ok()   { echo -e "\033[1;32m[OK]\033[0m $*"; }
warn() { echo -e "\033[1;33m[WARN]\033[0m $*"; }

command -v docker >/dev/null || die "Docker not found. Install Docker first."

# 0) Basic container checks
info "Checking containers..."
docker ps --format "table {{.Names}}\t{{.Status}}\t{{.Ports}}" | sed 's/^/[DOCKER] /'
docker inspect -f '{{.State.Running}}' "$NGINX_CONTAINER" >/dev/null 2>&1 || die "Container '$NGINX_CONTAINER' is not running."
docker inspect -f '{{.State.Running}}' "$UPSTREAM_CONTAINER" >/dev/null 2>&1 || warn "Upstream container '$UPSTREAM_CONTAINER' is not running. You may see 502 until it is."

# 1) Ensure network exists and both containers are attached
info "Ensuring Docker network '$DOCKER_NETWORK' exists and containers are attached..."
docker network inspect "$DOCKER_NETWORK" >/dev/null 2>&1 || docker network create "$DOCKER_NETWORK" >/dev/null
docker network connect "$DOCKER_NETWORK" "$NGINX_CONTAINER" >/dev/null 2>&1 || true
docker network connect "$DOCKER_NETWORK" "$UPSTREAM_CONTAINER" >/dev/null 2>&1 || true
ok "Network ready."

# 2) Verify certs are readable inside the nginx container
info "Verifying certificates inside container..."
docker exec -i "$NGINX_CONTAINER" sh -lc "ls -l $CERT_FULLCHAIN_CONT $CERT_PRIVKEY_CONT >/dev/null 2>&1" \
  || die "Certs not found/readable in container. Ensure your compose mounts:
  - $CERT_FULLCHAIN_CONT (fullchain)
  - $CERT_PRIVKEY_CONT (privkey)"
ok "Certificates present."

# 3) Drop a minimal HTTPS vhost in /etc/nginx/conf.d/
info "Installing HTTPS vhost for $DOMAIN..."
HTTP_REDIRECT_BLOCK=""
if [ "$ENABLE_HTTP_REDIRECT" = "true" ]; then
  HTTP_REDIRECT_BLOCK=$(cat <<'REDIR'
server {
  listen 80;
  server_name DOMAIN_PLACEHOLDER;
  return 301 https://$host$request_uri;
}
REDIR
)
  HTTP_REDIRECT_BLOCK="${HTTP_REDIRECT_BLOCK/DOMAIN_PLACEHOLDER/$DOMAIN}"
fi

docker exec -i "$NGINX_CONTAINER" sh -lc "cat > /etc/nginx/conf.d/${DOMAIN}.conf" <<EOF
# Auto-generated by setup_nginx_https.sh
server {
  listen 443 ssl http2;
  server_name $DOMAIN;

  ssl_certificate     $CERT_FULLCHAIN_CONT;
  ssl_certificate_key $CERT_PRIVKEY_CONT;

  # Minimal secure defaults
  ssl_protocols TLSv1.2 TLSv1.3;
  ssl_prefer_server_ciphers off;

  # Proxy to upstream inside Docker
  proxy_http_version 1.1;
  proxy_read_timeout 60s;
  proxy_send_timeout 60s;
  proxy_connect_timeout 5s;

  proxy_set_header Host \$host;
  proxy_set_header X-Real-IP \$remote_addr;
  proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
  proxy_set_header X-Forwarded-Proto https;

  location / {
    proxy_pass http://$UPSTREAM_HOST:$UPSTREAM_PORT;
  }
}

$HTTP_REDIRECT_BLOCK
EOF
ok "Vhost written to /etc/nginx/conf.d/${DOMAIN}.conf"

# 4) Test and reload nginx
info "Testing nginx config..."
docker exec -i "$NGINX_CONTAINER" nginx -t >/dev/null || {
  docker exec -i "$NGINX_CONTAINER" sh -lc 'tail -n +1 /var/log/nginx/error.log || true'
  die "nginx -t failed."
}
docker exec -i "$NGINX_CONTAINER" nginx -s reload >/dev/null || die "Failed to reload nginx."
ok "nginx reloaded."

# 5) Verify the vhost is loaded
info "Verifying 443 listener and server_name in running config..."
docker exec -i "$NGINX_CONTAINER" sh -lc "nginx -T | grep -E 'listen 443|server_name $DOMAIN' -n" || \
  die "Did not find a 443 listener or server_name '$DOMAIN' in nginx -T."

# 6) Ensure host port 443 is published (docker-proxy listening)
info "Checking host port 443 is bound..."
if ! ss -ltnp | grep -q ':443'; then
  warn "Host 443 is not bound. Ensure your nginx service publishes '443:443' in compose."
else
  ok "Host 443 is listening."
fi

# 7) Sanity checks (container + host + DNS)
info "Sanity: curl from inside container (should return headers, maybe 200/301/404)..."
docker exec -i "$NGINX_CONTAINER" sh -lc "apk add --no-cache curl >/dev/null 2>&1 || true; curl -skI https://localhost || true"

info "Sanity: curl from host against localhost:443..."
curl -vkI https://localhost || true

info "Sanity: curl from host against https://$DOMAIN ..."
curl -vkI "https://$DOMAIN" || true

# 8) Quick upstream reachability check (optional)
info "Checking upstream reachability from nginx -> http://$UPSTREAM_HOST:$UPSTREAM_PORT ..."
docker exec -i "$NGINX_CONTAINER" sh -lc "curl -sS http://$UPSTREAM_HOST:$UPSTREAM_PORT >/dev/null && echo 'Upstream reachable' || echo 'Upstream not reachable (you might see 502 until it is)'" || true

ok "Done. If you saw HTTP/2 200/301/404 for the curls, 443 is good to go."
